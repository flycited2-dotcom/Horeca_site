#!/bin/sh
# Точка входа контейнеров магазина. Настройки приходят из .env сервера при запуске
# контейнера, поэтому кэш настроек, маршрутов и шаблонов собирает здесь сам сайт (PHP-FPM),
# а не сборка образа. Очереди и планировщик читают настройки при старте без кэша.
set -e

if [ "$1" = "php-fpm" ]; then
    php artisan optimize
fi

exec "$@"
